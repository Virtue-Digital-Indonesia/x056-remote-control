const assert = require('node:assert/strict');
const { chromium } = require('/usr/local/lib/node_modules/playwright');
const base = process.argv[2] || 'http://127.0.0.1:8772';
const token = 'browser-fixture-token-0123456789';
(async () => {
  const browser = await chromium.launch({args:['--no-sandbox']});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:960}});
    await context.addInitScript(t => localStorage.setItem('x056_token', t), token);
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const create = async name => {
      const r = await context.request.post(base+'/api/chats', {headers:{Authorization:'Bearer '+token}, data:{requestId:crypto.randomUUID(),name,provider:'claude'}});
      assert.equal(r.status(), 201); return r.json();
    };
    const first = await create('Proposal planning'), second = await create('Research notes');
    await page.goto(base);
    const link = page.locator('#crChatTab'); await link.waitFor();
    assert.equal(await link.getAttribute('href'), '/chat');
    await link.click(); await page.locator('#rcChatWelcome h1').waitFor();
    assert.equal(new URL(page.url()).pathname, '/chat');
    await page.locator(`[data-chat="${first.id}"]`).click();
    await page.locator('#rcChatFiles').waitFor();
    assert.equal(new URL(page.url()).pathname, '/chat/'+first.id);
    await page.locator('#prompt').fill('Unsent proposal notes');
    await page.locator(`[data-chat="${second.id}"]`).click();
    await page.waitForFunction(id => document.querySelector('[data-chat="'+id+'"]').classList.contains('selected'), second.id);
    await page.goBack();
    await page.waitForFunction(() => document.querySelector('#prompt').value === 'Unsent proposal notes');
    assert.equal(new URL(page.url()).pathname, '/chat/'+first.id);
    await page.goForward();
    await page.waitForFunction(id => document.querySelector('[data-chat="'+id+'"]').classList.contains('selected'), second.id);
    await page.reload(); await page.locator('#rcChatFiles').waitFor();
    assert.equal(new URL(page.url()).pathname, '/chat/'+second.id);
    const deep = await context.newPage(); await deep.goto(base+'/chat/'+first.id);
    await deep.locator('#rcChatFiles').waitFor();
    assert.equal(await deep.locator('#prompt').inputValue(), 'Unsent proposal notes'); await deep.close();
    await page.locator('#rcChatMore').click();
    await page.locator('.rc-chat-actions-dialog').waitFor();
    assert(await page.locator('.rc-chat-action-list [data-copy]').isVisible());
    await page.screenshot({path:'/tmp/rc-chat-actions-refined.png'}); await page.keyboard.press('Escape');
    await page.locator('#rcChatTools').click();
    await page.locator('.rc-chat-capability').waitFor();
    assert.equal(await page.locator('[data-kind=plugin]').getAttribute('aria-pressed'), 'true');
    await page.locator('[data-kind=skill]').click();
    assert.equal(await page.locator('[data-kind=skill]').getAttribute('aria-pressed'), 'true');
    await page.locator('#rcToolsSearch').fill('nothing-matches');
    await page.getByText('No matching tools', {exact:true}).waitFor();
    await page.locator('#rcToolsSearch').fill('');
    await page.locator('.rc-chat-capability input').check();
    await page.locator('#rcToolsRequired').filter({hasText:'1 required'}).waitFor();
    await page.locator('.rc-chat-capability input').waitFor({state:'visible'});
    await page.screenshot({path:'/tmp/rc-chat-tools-refined.png'});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/rc-chat-tools-mobile.png'});
    assert(await page.locator('.rc-chat-tools-dialog').evaluate(e => e.scrollWidth <= e.clientWidth));
    await page.keyboard.press('Escape'); await page.setViewportSize({width:1440,height:960});
    await page.locator('#rcChatReference').click();
    const groups = page.locator('.rc-reference-group'); assert(await groups.count() >= 2);
    const website = groups.filter({has:page.getByRole('heading',{name:'Website refresh'})});
    assert.equal(await website.locator('button').count(), 3);
    await page.screenshot({path:'/tmp/rc-chat-references-grouped.png'});
    await page.getByRole('searchbox',{name:'Search references'}).fill('Website refresh');
    assert.equal(await groups.count(), 1); assert.equal(await groups.locator('button').count(), 3);
    await page.getByRole('searchbox',{name:'Search references'}).fill('accessibility');
    assert.equal(await groups.count(), 1); assert.equal(await groups.locator('button').count(), 1);
    await groups.locator('button').click();
    await page.locator('.rc-chat-reference').filter({hasText:'Review accessibility findings'}).waitFor();
    await page.locator('#rcChatReference').click();
    assert(await page.locator('.rc-reference-group button').filter({hasText:'Review accessibility findings'}).isDisabled());
    await page.keyboard.press('Escape');
    await page.goto(base+'/chat/no-such-chat');
    await page.getByRole('heading',{name:'Chat unavailable',exact:true}).waitFor();
    assert(!(await page.locator('#prompt').isVisible()));
    await page.locator('#rcChatControl').click();
    await page.locator('.cr-task').first().waitFor(); assert.equal(new URL(page.url()).pathname, '/');
    await page.goBack(); await page.getByRole('heading',{name:'Chat unavailable',exact:true}).waitFor();
    const signedOut = await browser.newContext();
    const login = await signedOut.newPage(); login.on('pageerror', e => errors.push(e.message));
    await login.goto(base+'/chat/'+first.id);
    await login.locator('#gateToken').fill(token); await login.locator('#gateTokenBtn').click();
    await login.locator('#rcChatFiles').waitFor();
    assert.equal(new URL(login.url()).pathname, '/chat/'+first.id);
    await signedOut.close();
    assert.deepEqual(errors, []);
    console.log('Chat routes, refresh, Back/Forward, drafts, actions, Tools, grouped references, and mobile passed.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
